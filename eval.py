	#print("probs")
	#print(USC.test_srbb_method_params(device, args.n_qubits)(params, None, False))
	#qml.draw_mpl(USC.test_srbb_method_params(device, args.n_qubits), decimals= 2)(params, None, False)
	#plt.show()
	#input()

	if args.state: 
		return U_tot, initial_state
	else:
		return U_approx, initial_state

		

