def cost(params, X, Y_ideal, n_qubit, loss, SU_ideal, x_max, rot_count, U_ideal, listSU, opt, state, device, initial_state, device_type):
	"""
	Choose which cost function to calculate
	
	Args:
		params (np.array): List of theta parameter that are trained
		X (): the training dataset
		Y_ideal (): the ideal density matrices
		n_qubit (int): number of qubits
		loss (str): Which loss to use
		SU_ideal (np.array): the ideal matrix
		x_max (int): number of ProdT_factors and M_factors
		rot_count (int): number of rot 
		U_ideal (np.array): the approximated matrix
		listSU (): list of all 2^n_qubits possibile SU
		opt (str): selected otpimizer: 'Adam' or 'Nelder_Mead'
		state (bool): if true train the phase, if false train the modulo

	Returns:
		loss: the loss value 
	
	"""
    
	if loss == 'trace_distance' or loss == 'fidelity':
		
		predictions = [USC.make_circuit_qnode(device, n_qubit, device_type)(params, x_max, rot_count, X[i], [], initial_state, state) for i in range(len(X))]
		
		predictions, states, probs = zip(*predictions)
		predictions, states, probs = list(predictions), list(states), list(probs)
		
		if loss == 'trace_distance':
			return losses.traceDistanceLoss(Y_ideal, predictions)
		elif loss == 'fidelity':
			return losses.fidelityLoss(Y_ideal, predictions)
	elif loss == 'frob':
		return losses.frobeniusLoss(params, x_max, SU_ideal, rot_count, U_ideal, listSU, opt, state, n_qubit, device)
	elif loss == 'hellinger':
		predictions = [USC.make_circuit_qnode(device, n_qubit, device_type)(params, x_max, rot_count, X[i], [], initial_state, state) for i in range(len(X))]
		#print(predictions[0][0]._value)
		#print(predictions[0][1]._value)
		#print(Y_ideal)
		#input()
		# Stack the predictions into a PennyLane numpy array for differentiable processing
		#predictions_array = np.array(predictions)
		probs = []
		for pred in predictions:
			z1, z2, zz = pred
			
			p00 = 0.25 * (anp.array(1.0) + z1 + z2 + zz)
			p01 = 0.25 * (anp.array(1.0) + z1 - z2 - zz)
			p10 = 0.25 * (anp.array(1.0) - z1 + z2 - zz)
			p11 = 0.25 * (anp.array(1.0) - z1 - z2 + zz)

			probs.append(anp.stack([p00, p01, p10, p11]))
		#print(probs[-1])
		
		return losses.hellingerLoss(Y_ideal, probs)

def training(X_train, Y_ideal, listdet, listSU, SU_ideal, dir, x_max, U_ideal, device, circuit, pathName, state, args, initial_state, index):	
	"""
	Execute the training of the neural network
	Args:
		X_train (): the training dataset
		Y_ideal (): the ideal density matrices
		batch_size (int): the batch size
		learning_rate (float): the learning rate value
		epochs (int): how many epoch of training
		loss (str): which loss function to use
		optimizer (str): which optimizer to use (Adam or Nelder_Mead)
		num_layer (int): number of layer of VQC
		n_qubit (int): number of qubits
		listdet (): list of determinant roots of the different 2^n possibilities of SU
		listSU (): list of all 2^n_qubits possibile SU
		SU_ideal (np.array): the ideal matrix
		dir (str): directory where to save/load file
		x_max (int): number of ProdT_factors and M_factors
		U_ideal (np.array): the approximated matrix
		device (str): device used
		circuit (): which circuit to approximate
		rot_count (int): number of rot 
		pathName (str):Name given by the options chosen in arguments
		path (str): where to save the files named with pathName
		state (bool): if true train the phase, if false train the modulo

	Returns
		params (): trained parameters
	    U_approx (np.array): approximated U
		cost_new (float): the value of the cost function
		norm[np.argmin(norm)] (float): the right norm value
		SU_approx (np.array): the approximated SU
		listSU[np.argmin(norm)] (np.array): the right SU
		rot_count (int): number of rotations
	"""
	

	params, rot_count=USC.Theta_array_gen(state, args.n_qubits)

	if args.opt=='Adam':
		opt=qml.AdamOptimizer(stepsize=args.lr)
	elif args.opt=='GDO':
		opt=qml.GradientDescentOptimizer(stepsize=args.lr)
	else:
		opt=qml.QNGOptimizer(stepsize=args.lr)

	if args.opt=='Nelder_Mead':
		params=scipy.optimize.fmin(func=losses.frobeniusLoss, x0=params, args=(x_max, SU_ideal, rot_count, U_ideal, listSU, args.opt, state, args.n_qubits, device, initial_state), xtol=10**(-15), ftol=10**(-15),maxiter=10**20,maxfun=10**20)
		
		print(params)
		cost_new=0.0

		if not state:
			fileParams = open(args.path + str(args.n_qubits) + 'qubit/' + str(index) + '/' + 'paramsModulo' + pathName + '.obj', 'wb')
		else:
			fileParams = open(args.path + str(args.n_qubits) + 'qubit/' + str(index) + '/' + 'paramsPhase' + pathName + '.obj', 'wb')
							
		pickle.dump(params, fileParams)
		fileParams.close()

		SU_approx = qml.matrix(USC.make_circuit_qnode(device, args.n_qubits, args.device))(params, x_max, rot_count, [], [], initial_state, state)
		utils.format_matrix(SU_approx)
		
	else:
		for e in range(args.epochs):
			print("EPOCH: ", e)
			for b in range(0, len(X_train), args.batch_size):
				if (b + args.batch_size) <= len(X_train):
					X_batch = [X_train[i] for i in range(b, b + args.batch_size)]
					Y_batch = [Y_ideal[i] for i in range(b, b + args.batch_size)]
				else:
					X_batch = [X_train[i] for i in range(b, len(X_train))]
					Y_batch = [Y_ideal[i] for i in range(b, len(X_train))]
					
				if args.opt == 'Adam':
					params, cost_new = opt.step_and_cost(lambda v: cost(v, X_batch, Y_batch, args.n_qubits, args.loss, SU_ideal, x_max, rot_count, U_ideal, listSU, args.opt, state, device, initial_state, args.device),
																params)
			
				
			print("iteration: ", e, " cost: ", cost_new)
			
			SU_approx = qml.matrix(USC.make_circuit_qnode(device, args.n_qubits, args.device))(params, x_max, rot_count, [], [], initial_state, state)
			#print(SU_approx)
			#print(params)
			#format_matrix(SU_approx)
			if not state:
				fileParams = open(args.path + str(args.n_qubits) + 'qubit/' + str(index) + '/' + 'paramsModulo' + pathName + '.obj', 'wb')
			else:
				fileParams = open(args.path + str(args.n_qubits) + 'qubit/' + str(index) + '/' + 'paramsPhase' + pathName + '.obj', 'wb')
							
			pickle.dump(params, fileParams)
			fileParams.close()
			
			
			
	"""
	with open(dir + 'SU_Results' + '.txt', "a") as file:
		file.write("\nAPPROX SU:\n")
		file.write(format_matrix2(SU_approx))
	"""
	if state:
		#choose the right SU or U
		DELTA = []

		for SU in listSU:
			DELTA.append(SU - SU_approx)

		norm = []
		for d in DELTA:
			norm.append(cmath.sqrt(max(np.linalg.eig(((np.conj(d)).T) @ d)[0])))
			
		print("NORM:")
		for n in norm:
			print(n)

		print("\n DET:")
		for d in listdet:
			print(d)
		

		
		#print(listSU[np.argmin(norm)])	
		#input()
		U_approx = SU_approx * listdet[np.argmin(norm)]
		print(U_approx)

		print("ALL UNITARIES: ")
		for det in listdet:
			utils.format_matrix(SU_approx*det)

		
		print(" ")
		#format_matrix(U_approx)

		
		fileu_app = open(args.path + str(args.n_qubits) + 'qubit/' + str(index) + '/' + 'U_appPhase' + pathName + '.obj', 'wb')
		file_rot_count = open(args.path + str(args.n_qubits) + 'qubit/' + str(index) + '/' + 'rot_countPhase' + pathName + '.obj', 'wb')
					
		pickle.dump(U_approx, fileu_app)
		fileu_app.close()

		
						
		pickle.dump(rot_count, file_rot_count)
		file_rot_count.close()
	

		return params, U_approx, cost_new, norm[np.argmin(norm)], SU_approx, listSU[np.argmin(norm)], rot_count
	else:
		fileu_app = open(args.path + 'U_appModulo' + pathName + '.obj', 'wb')
		file_rot_count = open(args.path + 'rot_countModulo' + pathName + '.obj', 'wb')

		pickle.dump(SU_approx, fileu_app)
		fileu_app.close()

		
						
		pickle.dump(rot_count, file_rot_count)
		file_rot_count.close()

		return params, None, cost_new, None, SU_approx, None, rot_count
